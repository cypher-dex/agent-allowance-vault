// Writes packages/aevum/src/abis.ts from Foundry's build output, so the TypeScript side always
// matches the deployed contracts. Run after `forge build` (the Makefile's `build` target does it).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const out = process.argv[2] ?? "contracts/out";
const contracts = ["AllowanceVault", "IdentityRegistry", "ReputationRegistry"];
let ts = "// Generated by tools/gen-abis.mjs from contracts/out. Do not edit by hand.\n\n";
for (const name of contracts) {
  const { abi } = JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), "utf8"));
  const id = name[0].toLowerCase() + name.slice(1);
  ts += `export const ${id}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync("packages/aevum/src/abis.ts", ts);
console.log(`✓ wrote ABIs for ${contracts.join(", ")} to packages/aevum/src/abis.ts`);
